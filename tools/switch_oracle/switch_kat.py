"""Switch / Switch 2 whole-surface known answers from tegra_swizzle.

Calls ScanMountGoat's tegra_swizzle C API (swizzled_surface_size,
swizzle_surface with is_orin, block_height_mip0) for a list of mip-chain x
layer cases. Each case gets a deterministic linear surface (kat_fill, as
in tools/ps5_oracle/kat_common.h; layers one after another, mips back to
back inside a layer), swizzled by the library and hashed (FNV-1a 64).
tests/test_main.cpp rebuilds the same surface with texc_reswizzle_mip and
compares.

Koei Tecmo's Switch loader reads a tiled G1T payload straight into NVN
texture storage (nvnTextureGetStorageSize bytes, Hyrule Warriors: Age of
Calamity), and this library's surface layout matches every tiled sample.

Usage:
  python tools/switch_oracle/switch_kat.py > tests/switch_surface_kat.h
Environment:
  TEXC_TEGRA_SWIZZLE  path to tegra_swizzle_x64.dll
"""
import ctypes
import os

DLL = os.environ.get("TEXC_TEGRA_SWIZZLE",
                     r"C:\Users\SalP\Documents\Reversing\Switch\switch toolbox\tegra_swizzle_x64.dll")

# (texc format, block w, block h, block bytes)
FORMATS = {
    "BC1": (4, 4, 8), "BC7": (4, 4, 16), "RGBA8": (1, 1, 4),
    "ASTC_8x8": (8, 8, 16), "ASTC_6x6": (6, 6, 16), "ASTC_4x4": (4, 4, 16),
    "RAW64": (1, 1, 8), "RAW8": (1, 1, 1),
}
# (mode, format, w, h, mips, layers[, depth]); depth > 1 is a volume
CASES = [
    ("SWITCH", "BC1", 1024, 1024, 9, 1),
    ("SWITCH", "BC1", 1024, 1024, 9, 2),     # request's 704,512-byte layer stride
    ("SWITCH", "BC7", 256, 256, 9, 6),       # cube
    ("SWITCH", "RGBA8", 300, 70, 9, 1),
    ("SWITCH", "BC7", 37, 23, 6, 4),
    ("SWITCH", "ASTC_6x6", 256, 256, 4, 12),  # seeker_wt_pb2warray2-shaped
    ("SWITCH", "ASTC_8x8", 1024, 1024, 4, 9),  # feb07b83-shaped
    ("SWITCH", "ASTC_6x6", 64, 64, 4, 6),     # 00a9a209-shaped
    ("SWITCH", "RAW64", 32, 8, 1, 600),       # 1d019335-shaped
    ("SWITCH", "RAW8", 17, 1000, 10, 1),
    ("SWITCH", "BC1", 2048, 64, 12, 1),
    ("SWITCH", "RGBA8", 1, 1, 1, 1),
    ("SWITCH2", "BC1", 1024, 1024, 9, 2),
    ("SWITCH2", "RGBA8", 300, 70, 9, 3),
    ("SWITCH2", "ASTC_8x8", 512, 256, 7, 1),
    # volumes (G1T type 2)
    ("SWITCH2", "BC1", 512, 512, 1, 1, 64),    # Pokopia 0x85775f17-shaped
    ("SWITCH2", "RAW64", 256, 256, 1, 1, 16),  # Pokopia 0x9adae037-shaped
    ("SWITCH2", "RGBA8", 32, 32, 6, 1, 32),
    ("SWITCH", "ASTC_4x4", 32, 32, 1, 1, 32),  # 1d2796b4-shaped
    ("SWITCH", "RGBA8", 16, 16, 5, 1, 16),
    ("SWITCH", "BC7", 64, 64, 4, 1, 9),
    ("SWITCH", "RAW8", 37, 23, 5, 1, 3),
]


class BlockDim(ctypes.Structure):
    _fields_ = [("w", ctypes.c_uint32), ("h", ctypes.c_uint32), ("d", ctypes.c_uint32)]


def kat_seed(i):
    return (0x243F6A8885A308D3 + 0x9E3779B97F4A7C15 * (i + 1)) & 0xFFFFFFFFFFFFFFFF


def kat_fill(n, seed):
    s = seed or 1
    out = bytearray(n)
    m = 0xFFFFFFFFFFFFFFFF
    for i in range(n):
        s ^= s >> 12
        s ^= (s << 25) & m
        s ^= s >> 27
        out[i] = ((s * 0x2545F4914F6CDD1D) & m) >> 56
    return bytes(out)


def fnv(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    dll = ctypes.CDLL(DLL)
    dll.swizzled_surface_size.restype = ctypes.c_uint64
    dll.block_height_mip0.restype = ctypes.c_uint64
    dll.swizzle_surface.restype = ctypes.c_int64
    rows = []
    for i, case in enumerate(CASES):
        mode, fmt, w, h, mips, layers = case[:6]
        depth = case[6] if len(case) > 6 else 1
        bw, bh, bb = FORMATS[fmt]
        dim = BlockDim(bw, bh, 1)
        bh0 = dll.block_height_mip0(ctypes.c_uint64((h + bh - 1) // bh))
        tiled = dll.swizzled_surface_size(w, h, depth, ctypes.byref(dim), bh0, bb, mips, layers)
        lin = sum(((max(1, w >> m) + bw - 1) // bw) * ((max(1, h >> m) + bh - 1) // bh) *
                  max(1, depth >> m) * bb for m in range(mips)) * layers
        seed = kat_seed(1000 + i)
        src = kat_fill(lin, seed)
        dst = ctypes.create_string_buffer(tiled)
        dll.swizzle_surface(w, h, depth, src, len(src), dst, tiled, ctypes.byref(dim), bh0, bb,
                            mips, layers, 1 if mode == "SWITCH2" else 0)
        rows.append(f"    {{ TEXC_SWIZZLE_{mode}, TEXC_FORMAT_{fmt}, {w}, {h}, {depth}, {mips}, {layers}, "
                    f"{tiled}ull, {seed:#018x}ull, {fnv(dst.raw):#018x}ull }},")
    print("""/*
 * switch_surface_kat.h - Switch / Switch 2 whole-surface (mip chain x
 * layers) known answers, generated by tools/switch_oracle/switch_kat.py from
 * ScanMountGoat's tegra_swizzle (swizzle_surface, auto block height). The
 * linear input is kat_fill(seed) over every layer's mips back to back, each
 * volume mip's depth slices back to back.
 */
#ifndef TEXC_SWITCH_SURFACE_KAT_H
#define TEXC_SWITCH_SURFACE_KAT_H

#include <stdint.h>
#include "../include/tex_codec.h"

struct switch_surface_kat {
    texc_swizzle_mode mode;
    texc_format format;
    uint32_t w, h, depth, mips, layers;
    uint64_t total_size;
    uint64_t seed;
    uint64_t hash;
};

static const switch_surface_kat k_switch_surface_kat[] = {""")
    print("\n".join(rows))
    print("""};

#endif /* TEXC_SWITCH_SURFACE_KAT_H */""")


if __name__ == "__main__":
    main()
